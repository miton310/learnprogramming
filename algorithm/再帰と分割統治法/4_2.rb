# 1からNまでの和を計算する再帰関数（デバッグ出力付き）
# この関数は計算の過程を表示しながら1からNまでの合計を求めます

def func(n)
  # 再帰関数を呼び出したことを表示
  # この出力で、関数がどの順番で呼ばれているか確認できます
  puts "func(#{n}) を呼びました"
  
  # ベースケース（再帰の終了条件）
  # nが0の場合、和は0なので0を返します
  if n == 0
    return 0
  end
  
  # 再帰的に答えを求めて出力
  # まずfunc(n-1)を呼び出して、それにnを加えます
  # resultには「1からnまでの和」が格納されます
  result = n + func(n - 1)
  
  # 計算結果を表示
  # この出力で、どのように和が積み重なっていくか確認できます
  puts "#{n}までの和 = #{result}"
  
  return result
end

# === 使用例 ===
# func(5)を呼び出すと、以下のように表示されます:
# func(5) を呼びました
# func(4) を呼びました
# func(3) を呼びました
# func(2) を呼びました
# func(1) を呼びました
# func(0) を呼びました
# 1までの和 = 1
# 2までの和 = 3
# 3までの和 = 6
# 4までの和 = 10
# 5までの和 = 15

func(5)  # 実行してみましょう
