# ========================================
# アルゴリズム: 部分和問題 (Subset Sum Problem)
# ========================================
# 目的: 配列 a の要素から選んで合計を w にできるか判定
# アプローチ: 各要素について「選ぶ/選ばない」の2択を再帰的に探索
#
# func(i, w, a): 最初のi個の要素から合計wを作れるかを判定
# - i: 考慮する要素の個数
# - w: 目標の合計値
# - a: 元の配列
# ========================================

def func(i, w, a)
  # ベースケース: 要素が0個のとき
  # w == 0 なら成功（何も選ばずに0を作れる）
  # w != 0 なら失敗（作れない）
  if i == 0
    return w == 0  # Rubyでは式の結果がそのまま返り値になる
  end

  # パターン1: a[i - 1]を選ばない場合
  # → 残りのi-1個の要素で合計wを作れるか調べる
  return true if func(i -1, w, a)

  # パターン2: a[i - 1]を選ぶ場合
  # → 残りのi-1個の要素で合計(w - a[i-1])を作れるか調べる
  # a[i-1]を選んだので、目標値からその分を引く
  return true if func(i - 1, w - a[i - 1], a)

  # どちらも false の場合は false を返す
  # Rubyでは最後の式が自動的に返り値になるため、return を省略可能
  false
end

# ========================================
# 入力処理
# ========================================
# Ruby文法解説:
# - gets: 標準入力から1行読み込む
# - split: 空白で文字列を分割（配列になる）
# - map(&:to_i): 各要素に to_i メソッドを適用（文字列→整数変換）
#   &:to_i は { |x| x.to_i } の省略記法
# - 多重代入: n, w = [値1, 値2] で同時に複数の変数に代入
n, w = gets.split.map(&:to_i)  # n: 要素数, w: 目標の合計値
a = gets.split.map(&:to_i)      # a: 整数の配列

# ========================================
# 再帰関数の呼び出しと結果出力
# ========================================
# func(n, w, a): n個の要素すべてを考慮して合計wが作れるか判定
if func(n, w, a)
  puts "Yes"
else
  puts "No"
end

# ========================================
# 計算量: O(2^n)
# 各要素について「選ぶ/選ばない」の2択 → 2^n通りの組み合わせを探索
# ※ メモ化やDPで O(n*w) に改善可能
# ========================================