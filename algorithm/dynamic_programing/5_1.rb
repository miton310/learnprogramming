# Frog Jump問題を解くRubyコード
# カエルが石を飛び越えて移動する際の最小コストを求める動的計画法

# 十分大きい値を定義（無限大の代わり）
INF = Float::INFINITY

# 入力処理
n = gets.to_i  # 石の個数
h = gets.split.map(&:to_i)  # 各石の高さの配列

# 配列 dp を定義（配列全体を無限大で初期化）
dp = Array.new(n, INF)

# 初期条件：最初の石にいるときのコストは0
dp[0] = 0

# ループで各石までの最小コストを計算
(1...n).each do |i|
  if i == 1
    # 2番目の石は1番目の石からしか来られない
    dp[i] = (h[i] - h[i - 1]).abs
  else
    # それ以降は、1つ前か2つ前から来た場合の最小値
    dp[i] = [
      dp[i - 1] + (h[i] - h[i - 1]).abs,  # 1つ前の石から来る
      dp[i - 2] + (h[i] - h[i - 2]).abs   # 2つ前の石から来る
    ].min
  end
end

# 答えを出力：最後の石までの最小コスト
puts dp[n - 1]